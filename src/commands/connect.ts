/**
 * `mod8 connect` subcommand group.
 *
 *   mod8 connect <slug>              — onboard a new product
 *   mod8 connect list                — list connected products
 *   mod8 connect remove <slug>       — delete product config (does not touch repo)
 *   mod8 connect add-adapter <slug> <adapter>
 *                                    — store adapter creds (interactive prompt)
 *
 * The onboarding wizard scaffolds product.md.tmpl + a starter
 * policy.yaml inheriting from _defaults.  Phase 4: shows which
 * adapters are available + how to enable each.
 */

